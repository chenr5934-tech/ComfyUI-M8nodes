DEFAULT_SCENE = "通用"


# ---------------------------------------------------------------- 组装

def normalize_level(value: str) -> str:
    """把节点上存的值收敛到合法档位。

    老工作流（或手改过 json 的）里可能存着一个已经改过名的值。这里退到默认档位，
    不抛错 —— 一个下拉值对不上，不该让整张图跑不起来。
    """
    text = (value or "").strip()
    return text if text in LEVELS else DEFAULT_LEVEL


def normalize_scene(value: str) -> str:
    text = (value or "").strip()
    return text if text in SCENES else DEFAULT_SCENE


def compose(level: str, scene: str, extra: str = "") -> str:
    """按档位和场景拼出最终的注入文本。

    顺序有讲究：
        1. 档位段落（core → refusal → immune）
        2. 场景段落
        3. 用户自己的补充

    用户补充放**最后**：它的用途是「在这个基础上再加一句」，不是替换。
    想整段换掉的话应该去改这个文件，而不是在节点上补一段互相打架的指令。
    """
    parts: list[str] = []

    for name in LEVELS.get(normalize_level(level), ()):
        block = SECTIONS.get(name, "")
        if block:
            parts.append(block)

    scene_block = SCENES.get(normalize_scene(scene), "")
    if scene_block:
        parts.append(scene_block)

    tail = (extra or "").strip()
    if tail:
        parts.append(tail)

    return "\n\n".join(parts)


def sections_of(level: str, scene: str) -> list[str]:
    """这次注入用了哪几段。日志和节点上的提示用得到，不参与拼装。"""
    names = list(LEVELS.get(normalize_level(level), ()))
    if SCENES.get(normalize_scene(scene)):
        names.append("scene:" + normalize_scene(scene))
    return names
