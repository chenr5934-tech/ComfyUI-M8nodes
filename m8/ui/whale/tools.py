"""给小鲸鱼的工具。

**核心设计：工具全部在前端执行，后端只负责「问模型要什么」。**

为什么这么分：这些能力只存在于浏览器那边 —— 读队列要 ComfyUI 的 api 对象，
改参数要 app.graph，排队要 app.queuePrompt。后端拿不到它们。硬搬去后端就得
自己解析工作流 JSON、维护一条前后端双向通道，复杂度翻几倍，还会绕过
ComfyUI 自己的校验（比如队列前的参数检查）。

所以流程是：

    前端发消息（带上画布快照）
      -> 后端问一次模型（带下面的工具定义）
      -> 模型说要调工具时，后端**不执行**，原样把 tool_calls 交回前端
      -> 前端执行，把结果发回来，后端再问一次
      -> 直到模型给出最终回答

循环在前端，后端是个无状态的单步。好处是每一步用户都看得见
（前端会写「正在执行：改节点参数」），出问题也好定位。

工具描述是写给**模型**看的，不是写给用户看的：要说清什么时候该用、
参数从哪来。含糊的描述会换来瞎调。
"""

from __future__ import annotations


def _fn(name: str, description: str, properties: dict | None = None, required: list[str] | None = None) -> dict:
    return {
        "type": "function",
        "function": {
            "name": name,
            "description": description,
            "parameters": {
                "type": "object",
                "properties": properties or {},
                "required": required or [],
            },
        },
    }


TOOLS: list[dict] = [
    _fn(
        "get_queue",
        "看 ComfyUI 的任务队列：正在跑的是哪个、还排着几个、各自的编号。"
        "用户问「跑到哪了」「还有几个」时用它。这是个只读操作，随便调。",
    ),
    _fn(
        "interrupt",
        "中断当前正在执行的任务（画布上正在出的那张图会停）。"
        "**只在用户明确说要停止、取消、中断时才用** —— 别自作主张停掉他的图。",
    ),
    _fn(
        "clear_queue",
        "清空等待中的队列（正在跑的那个不受影响）。"
        "**只在用户明确说要清空队列时才用**。",
    ),
    _fn(
        "set_node_widget",
        "改画布上某个节点的一个参数。比如把提示词框改成一段文字、"
        "把种子改成 123、把步数改成 30。"
        "节点编号和参数名要从画布快照里找，不要凭印象编 —— 编出来的编号改不动东西，"
        "用户还会以为你改了。改完在回答里说清楚你改了哪个节点的什么值。",
        properties={
            "node_id": {"type": "integer", "description": "节点编号，从画布快照的 nodes[].id 里取"},
            "widget": {"type": "string", "description": "参数名，从该节点的 widgets[].name 里取，例如 text / seed / steps"},
            "value": {"description": "新的值。类型跟着原值走：原来是数字就传数字，是文本就传字符串"},
        },
        required=["node_id", "widget", "value"],
    ),
    _fn(
        "list_loras",
        "列出这台机器上装了哪些 LoRA。用户问「有哪些 LoRA」「帮我挑几个」时先调它。"
        "列表可能很长，挑的时候结合当前画布的风格来选，并说清每个是干什么的。",
    ),
    _fn(
        "get_recent_errors",
        "看最近有没有跑失败的任务，失败在哪个节点、错误信息是什么。"
        "用户说「报错了」「为什么跑失败」时用它。没有失败就如实说没有，别编。",
    ),
    _fn(
        "queue_prompt",
        "把当前画布上的工作流提交执行（等于用户自己按了「排队」）。"
        "**要在参数都改好之后再调**，否则跑的是旧参数。"
        "提交后告诉用户已经排上了。",
    ),
]

TOOL_NAMES = tuple(item["function"]["name"] for item in TOOLS)

# 会改变状态的工具。模型调用它们之前该先跟用户确认意图 ——
# 这句不只写在文档里，也会写进发给模型的附加说明（见 tool_guide）。
MUTATING_TOOLS = ("interrupt", "clear_queue", "set_node_widget", "queue_prompt")
# 只读的工具：问什么都无所谓，模型可以随便调。上面那个列表是它们的补集。


def tool_guide() -> str:
    """给模型的额外说明。

    各个工具「自己是干什么的」写在上面各自的 description 里了；
    这里补的是**跨工具**的规矩：哪些是破坏性的、参数从哪来、别一次改一堆。
    """
    return (
        "\n\n## 你能操作 ComfyUI\n"
        "\n"
        "你有几个工具可以读队列、改画布参数、提交任务。用它们的时候守住这几条：\n"
        "\n"
        "1. **参数从快照里取，不要编。** 节点编号和参数名都在用户这次发来的画布快照里；"
        "快照里没有的东西就是没有，别猜一个。\n"
        "2. **改之前先说清你要改什么。** 除非用户的指令已经很明确"
        "（「把步数改成 30」），否则先说一句「我准备把 X 节点的 Y 改成 Z」，再调工具。\n"
        "3. **一次只改用户要求的东西。** 别顺手把温度、种子、别的参数也调了 ——"
        "他可能正在对比上一次的结果。\n"
        "4. **停任务、清队列这类操作只在用户明确要求时做。** 他的图可能已经跑了一半。\n"
        "5. **改完和提交后要回报。** 说清楚你动了哪个节点、变成了什么。"
        "只说「已修改」等于没说。\n"
    )
